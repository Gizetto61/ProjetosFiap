# Função de conexão
def abrirConexao():
    try:
        conexao = oracledb.connect(user = DB_USER, password = DB_PASS, dsn = DB_DNS)
        return conexao
    except oracledb.Error as e:
        print(f'Erro ao conectar com o Oracle DB: {e}')
        return None

# Função para criar uma tabela
def criarTabela():
    # Comando SQL
    sql = """
    CREATE TABLE ALUNOS_PY(
        ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        NOME VARCHAR2(100) NOT NULL,
        EMAIL VARCHAR2(100) UNIQUE NOT NULL,
        CURSO VARCHAR2(50) DEFAULT 'ADS'
    )
    """
    # Abrindo conexão
    conexao = abrirConexao()
    # Verificando se a conexão existe
    if conexao:
        try:
            # Execução no banco
            cursor = conexao.cursor()
            cursor.execute(sql)
            print('Tabela ALUNOS_PY criada com sucesso!')
        except oracledb.Error as e:
            if "ORA-00955" in str(e):
                print('Tabela ALUNOS_PY já existe!')
            else:
                print(f'Erro ao criar a tabela: {e}')
        finally:
            conexao.close()

# CREATE / INSERT
def criarAluno(nome, email, curso):
    sql = f"INSERT INTO ALUNOS_PY(NOME, EMAIL, CURSO) VALUES (:1, :2, :3)"
    conexao = abrirConexao()
    try:
        cursor = conexao.cursor()
        cursor.execute(sql, (nome, email, curso))
        conexao.commit()
        print(f'Aluno: {nome} cadastrado com sucesso!')
    except oracledb.Error as e:
        print(f'Erro ao inserir o aluno {nome}: {e}')
    finally:
        conexao.close()

